function slugFromName(name) {
  return String(name || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function productSlug(product) {
  if (!product.image) return slugFromName(product.name);
  const file = product.image.split("/").pop();
  return file.replace(/\.[^.]+$/, "");
}

